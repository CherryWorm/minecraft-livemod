#!/usr/bin/env python3
"""Writes infra/mods.lock: every third-party jar with its Modrinth URL and SHA-512.

Images are built only from this file and each download is checked against it,
so a build can't silently pick up a changed jar.
"""
import json
import pathlib
import urllib.parse
import urllib.request

# role: which image gets the jar. server = prod and shadow, shadow = test server only.
MODS = [
    ("server", "fabric-api", "0.165.0+26.3"),
    ("server", "polymer", "0.18.5+26.3"),
    ("server", "fabricproxy-lite", "v2.12.0"),
    ("server", "spark", "1.10.187-fabric"),
    ("shadow", "carpet", "26.3"),
    ("velocity", "Ri89j7v5", "1.1.0"),
]


def fetch_version(slug, version):
    quoted = urllib.parse.quote(version, safe="")
    request = urllib.request.Request(
        f"https://api.modrinth.com/v2/project/{slug}/version/{quoted}",
        headers={"User-Agent": "living-mod/lock-mods"},
    )
    with urllib.request.urlopen(request, timeout=30) as response:
        return json.load(response)


def main():
    lines = ["# role\tfile\turl\tsha512\t(generated by scripts/lock-mods.py)"]
    for role, slug, version in MODS:
        data = fetch_version(slug, version)
        file = next((f for f in data["files"] if f["primary"]), data["files"][0])
        lines.append("\t".join((role, file["filename"], file["url"], file["hashes"]["sha512"])))
        print(f"{role:8} {file['filename']}")
    path = pathlib.Path(__file__).resolve().parent.parent / "infra" / "mods.lock"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
